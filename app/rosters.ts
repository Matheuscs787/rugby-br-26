export type RosterPlayer = {
  name: string;
  number: number;
};

export type TeamRoster = {
  source: string;
  players: RosterPlayer[];
};

const FIRST_DIVISION_SHEET =
  "https://plataforma.sporti.com.br/cbru/campeonatos/2026-6-super-12---primeira-divisao---masculino-rugby-xv-masculino/sumula/";
const SECOND_DIVISION_SHEET =
  "https://plataforma.sporti.com.br/cbru/campeonatos/2026-6-super-12---primeira-divisao---masculino-rugby-xv-masculino1/sumula/";

function roster(
  division: 1 | 2,
  sheet: string,
  players: Array<[number, string]>,
): TeamRoster {
  return {
    source: `${division === 1 ? FIRST_DIVISION_SHEET : SECOND_DIVISION_SHEET}${sheet}`,
    players: players.map(([number, name]) => ({ number, name })),
  };
}

